"""Register of synthetic brand children.

How a child comes into being (every step is an audit entry):

  1. propose      candidates are generated from text alone
  2. endorse      two different people endorse a candidate (four-eyes)
  3. extend       further images of the same child, guided by reference images
  4. approve      a reviewer approves the training set
  5. train        a LoRA is trained on exactly that set
  6. freeze       the version becomes immutable and usable
  7. pool/assign  the child waits in the internal pool or is locked to one brand
  8. grow         a new version with a higher age, derived from the previous one

Rules enforced here:
  - every image used for a child was generated by this system, passed the
    safety gate and carries its own C2PA signature; nothing can be uploaded
  - a child belongs to exactly one engine and at most one brand
  - frozen versions never change
"""

from __future__ import annotations

import hashlib
import io
import json
from dataclasses import dataclass, field
from enum import Enum
from pathlib import Path
from typing import Any, Protocol

from PIL import Image

from nps.audit.chain import AuditLog
from nps.core.hashing import sha256_bytes, sha256_image, sha256_json
from nps.engine.base import Capability, Engine, GenerationInputs, GenerationRequest
from nps.intake.brief import MAX_AGE_V1, MIN_AGE_V1, screen_text
from nps.provenance.c2pa_sign import C2paSigner, read_credentials
from nps.safety.gate import SafetyGate

REGISTER_SCOPE = "identity-register"
MIN_DATASET_IMAGES = 8
IMAGE_SIZE = 1024


class RegisterError(Exception):
    """The requested step is not allowed in the current state."""


class IdentityStatus(str, Enum):
    CANDIDATE = "candidate"
    SELECTED = "selected"
    POOL = "pool"
    EXCLUSIVE = "exclusive"
    REJECTED = "rejected"
    RETIRED = "retired"


class VersionStage(str, Enum):
    DRAFT = "draft"
    DATASET_APPROVED = "dataset_approved"
    TRAINED = "trained"
    FROZEN = "frozen"


@dataclass
class IdentityImage:
    sha256: str  # of the signed file
    pixels_sha256: str
    role: str  # "candidate" or "dataset"
    version: int
    seed: int


@dataclass
class IdentityVersion:
    number: int
    age_years: int
    parent: int | None
    stage: VersionStage = VersionStage.DRAFT
    images: list[IdentityImage] = field(default_factory=list)
    dataset: list[str] = field(default_factory=list)
    dataset_approved_by: str | None = None
    lora_sha256: str | None = None
    training_spec_sha256: str | None = None
    frozen_by: str | None = None


@dataclass
class Identity:
    identity_id: str
    engine: str
    description: str
    batch_id: str
    created_by: str
    status: IdentityStatus = IdentityStatus.CANDIDATE
    brand: str | None = None
    endorsed_by: list[str] = field(default_factory=list)
    versions: dict[int, IdentityVersion] = field(default_factory=dict)
    blocked_images: int = 0
    events: list[dict[str, Any]] = field(default_factory=list)

    @property
    def latest(self) -> IdentityVersion:
        return self.versions[max(self.versions)]


@dataclass(frozen=True)
class TrainingSpec:
    identity_id: str
    version: int
    engine: str
    base_model_revision: str | None
    dataset_sha256: tuple[str, ...]
    rank: int = 16
    steps: int = 1500
    learning_rate: float = 1e-4
    seed: int = 0

    def as_dict(self) -> dict[str, Any]:
        return {
            "identity_id": self.identity_id,
            "version": self.version,
            "engine": self.engine,
            "base_model_revision": self.base_model_revision,
            "dataset_sha256": list(self.dataset_sha256),
            "rank": self.rank,
            "steps": self.steps,
            "learning_rate": self.learning_rate,
            "seed": self.seed,
        }


class Trainer(Protocol):
    name: str
    production: bool

    def train(self, spec: TrainingSpec, images: list[Image.Image]) -> bytes:
        """Return the trained LoRA weights."""
        ...


class MockTrainer:
    """Produces placeholder weights derived from the spec. Trains nothing."""

    name = "mock"
    production = False

    def train(self, spec: TrainingSpec, images: list[Image.Image]) -> bytes:
        return b"mock-lora:" + sha256_json(spec.as_dict()).encode("ascii")


def read_register(log: AuditLog) -> dict[str, Identity]:
    """Replay the verified chain into the current state of all children."""
    identities: dict[str, Identity] = {}
    for entry in log.verify():
        if entry.campaign_id != REGISTER_SCOPE or entry.asset_id is None:
            continue
        payload, event = entry.payload, entry.event
        if event == "identity_proposed":
            identity = Identity(
                identity_id=entry.asset_id,
                engine=payload["engine"],
                description=payload["description"],
                batch_id=payload["batch_id"],
                created_by=payload["created_by"],
            )
            identity.versions[1] = IdentityVersion(1, payload["age_years"], None)
            identities[entry.asset_id] = identity
        identity = identities[entry.asset_id]
        identity.events.append(
            {"seq": entry.seq, "timestamp": entry.timestamp, "event": event, "hash": entry.hash}
        )
        if event == "identity_image":
            identity.versions[payload["version"]].images.append(
                IdentityImage(
                    sha256=payload["sha256"],
                    pixels_sha256=payload["pixels_sha256"],
                    role=payload["role"],
                    version=payload["version"],
                    seed=payload["seed"],
                )
            )
        elif event == "identity_image_blocked":
            identity.blocked_images += 1
        elif event == "candidate_endorsed":
            identity.endorsed_by.append(payload["reviewer"])
        elif event == "candidate_selected":
            identity.status = IdentityStatus.SELECTED
        elif event == "identity_rejected":
            identity.status = IdentityStatus.REJECTED
        elif event == "dataset_approved":
            version = identity.versions[payload["version"]]
            version.dataset = payload["images"]
            version.dataset_approved_by = payload["reviewer"]
            version.stage = VersionStage.DATASET_APPROVED
        elif event == "lora_trained":
            version = identity.versions[payload["version"]]
            version.lora_sha256 = payload["weights_sha256"]
            version.training_spec_sha256 = payload["spec_sha256"]
            version.stage = VersionStage.TRAINED
        elif event == "version_frozen":
            version = identity.versions[payload["version"]]
            version.stage = VersionStage.FROZEN
            version.frozen_by = payload["by"]
        elif event == "identity_pooled":
            identity.status = IdentityStatus.POOL
        elif event == "identity_assigned":
            identity.status = IdentityStatus.EXCLUSIVE
            identity.brand = payload["brand"]
        elif event == "identity_retired":
            identity.status = IdentityStatus.RETIRED
        elif event == "version_started":
            identity.versions[payload["version"]] = IdentityVersion(
                payload["version"], payload["age_years"], payload["parent"]
            )
    return identities


def _name(value: str, role: str) -> None:
    if not value.strip():
        raise RegisterError(f"a name is required for '{role}'")


def _age(age_years: int) -> None:
    if not MIN_AGE_V1 <= age_years <= MAX_AGE_V1:
        raise RegisterError(f"age {age_years} is outside the v1 range {MIN_AGE_V1} to {MAX_AGE_V1}")


class IdentityRegister:
    def __init__(
        self,
        out_dir: Path,
        engine: Engine,
        gate: SafetyGate,
        signer: C2paSigner | None,
        log: AuditLog | None = None,
        trainer: Trainer | None = None,
    ) -> None:
        self._out = Path(out_dir)
        self._engine = engine
        self._gate = gate
        self._signer = signer
        self._trainer = trainer
        self.log = log or AuditLog(self._out / "audit.jsonl")

    # -- reading ---------------------------------------------------------

    def all(self) -> dict[str, Identity]:
        return read_register(self.log)

    def get(self, identity_id: str) -> Identity:
        identity = self.all().get(identity_id)
        if identity is None:
            raise RegisterError(f"unknown identity '{identity_id}'")
        return identity

    def image_path(self, identity_id: str, sha256: str) -> Path:
        return self._out / "identities" / identity_id / "images" / f"{sha256}.png"

    def lora_path(self, identity_id: str, version: int) -> Path:
        return self._out / "identities" / identity_id / f"v{version}" / "lora.safetensors"

    # -- helpers ---------------------------------------------------------

    def _record(self, identity_id: str, event: str, payload: dict[str, Any]) -> None:
        self.log.append(
            campaign_id=REGISTER_SCOPE, asset_id=identity_id, event=event, payload=payload
        )

    def _require_engine(self, identity: Identity) -> None:
        name = self._engine.describe().name
        if identity.engine != name:
            raise RegisterError(
                f"identity '{identity.identity_id}' belongs to engine '{identity.engine}', "
                f"not '{name}'"
            )

    def _generate_image(
        self,
        identity_id: str,
        *,
        version: int,
        role: str,
        prompt: str,
        seed: int,
        references: tuple[Image.Image, ...] = (),
    ) -> IdentityImage | None:
        """Generate, gate and sign one image. Returns None if the gate blocks it."""
        if self._signer is None:
            raise RegisterError("images of a child need a C2PA signer; none is configured")
        request = GenerationRequest(
            prompt=prompt,
            seed=seed,
            width=IMAGE_SIZE,
            height=IMAGE_SIZE,
            reference_sha256=tuple(sha256_image(image) for image in references),
        )
        result = self._engine.generate(request, GenerationInputs(references=references))
        safety = self._gate.evaluate(result.image, result.manifest)
        if not safety.passed:
            self._record(
                identity_id,
                "identity_image_blocked",
                {"version": version, "role": role, "seed": seed, "check": safety.model_dump()},
            )
            return None

        buffer = io.BytesIO()
        result.image.save(buffer, "PNG")
        signed = self._signer.sign_png(
            buffer.getvalue(),
            title=f"{identity_id}-v{version}-{role}.png",
            asset={"identity_id": identity_id, "version": version, "role": role, "ai_generated": True},
        )
        image = IdentityImage(
            sha256=sha256_bytes(signed),
            pixels_sha256=sha256_image(result.image),
            role=role,
            version=version,
            seed=seed,
        )
        path = self.image_path(identity_id, image.sha256)
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(signed)
        self._record(
            identity_id,
            "identity_image",
            {
                "version": version,
                "role": role,
                "seed": seed,
                "sha256": image.sha256,
                "pixels_sha256": image.pixels_sha256,
                "manifest": result.manifest.model_dump(),
                "check": safety.model_dump(),
                "gate_production": self._gate.production,
                "engine_production": self._engine.describe().production,
            },
        )
        return image

    def _load_verified(self, identity_id: str, sha256: str) -> Image.Image:
        """Load an image of this child and prove it is ours and unchanged."""
        path = self.image_path(identity_id, sha256)
        if not path.is_file():
            raise RegisterError(f"image {sha256[:12]} of '{identity_id}' is missing")
        data = path.read_bytes()
        if sha256_bytes(data) != sha256:
            raise RegisterError(f"image {sha256[:12]} of '{identity_id}' was changed on disk")
        report = read_credentials(data)
        if report is None or not report.intact or (report.asset or {}).get("identity_id") != identity_id:
            raise RegisterError(f"image {sha256[:12]} does not carry this child's valid signature")
        image = Image.open(io.BytesIO(data))
        image.load()
        return image.convert("RGB")

    @staticmethod
    def _seed(identity_id: str, version: int, index: int) -> int:
        digest = hashlib.sha256(f"{identity_id}:{version}:{index}".encode("utf-8")).digest()
        return int.from_bytes(digest[:4], "big")

    @staticmethod
    def _prompt(description: str, age_years: int, variation: str = "") -> str:
        parts = [f"portrait of a child, {age_years} years old", description, "fully clothed", variation]
        return ". ".join(part for part in parts if part)

    # -- 1. propose ------------------------------------------------------

    def propose(self, description: str, age_years: int, count: int, created_by: str) -> list[str]:
        """Generate candidates from text alone. Each candidate is its own identity."""
        _name(created_by, "created_by")
        _age(age_years)
        if not 1 <= count <= 12:
            raise RegisterError("between 1 and 12 candidates can be proposed at once")
        excluded = screen_text(description)
        if excluded:
            raise RegisterError(f"description contains excluded terms: {', '.join(excluded)}")
        if self._signer is None:
            raise RegisterError("images of a child need a C2PA signer; none is configured")

        engine = self._engine.describe().name
        existing = len(self.all())
        batch_id = sha256_json([engine, description, age_years, existing])[:12]
        created: list[str] = []
        for index in range(count):
            identity_id = "id-" + sha256_json([batch_id, index])[:12]
            self._record(
                identity_id,
                "identity_proposed",
                {
                    "engine": engine,
                    "description": description,
                    "age_years": age_years,
                    "batch_id": batch_id,
                    "created_by": created_by,
                },
            )
            self._generate_image(
                identity_id,
                version=1,
                role="candidate",
                prompt=self._prompt(description, age_years),
                seed=self._seed(identity_id, 1, 0),
            )
            created.append(identity_id)
        return created

    # -- 2. four-eyes selection -----------------------------------------

    def endorse(self, identity_id: str, reviewer: str) -> IdentityStatus:
        """Two different people must endorse a candidate before it is selected."""
        _name(reviewer, "reviewer")
        identity = self.get(identity_id)
        if identity.status is not IdentityStatus.CANDIDATE:
            raise RegisterError(f"identity '{identity_id}' is not a candidate")
        if not identity.versions[1].images:
            raise RegisterError(f"identity '{identity_id}' has no image that passed the safety gate")
        normalised = reviewer.strip().casefold()
        if normalised in (name.strip().casefold() for name in identity.endorsed_by):
            raise RegisterError("the second endorsement must come from a different person")
        self._record(identity_id, "candidate_endorsed", {"reviewer": reviewer})
        if identity.endorsed_by:
            self._record(
                identity_id, "candidate_selected", {"reviewers": [*identity.endorsed_by, reviewer]}
            )
            return IdentityStatus.SELECTED
        return IdentityStatus.CANDIDATE

    def reject(self, identity_id: str, by: str, reason: str = "") -> None:
        _name(by, "by")
        identity = self.get(identity_id)
        if identity.status is not IdentityStatus.CANDIDATE:
            raise RegisterError(f"identity '{identity_id}' is not a candidate")
        self._record(identity_id, "identity_rejected", {"by": by, "reason": reason})

    # -- 3. extend the training set --------------------------------------

    def extend_dataset(self, identity_id: str, count: int) -> list[IdentityImage]:
        """Generate further images of the child, guided by images it already has."""
        identity = self.get(identity_id)
        self._require_engine(identity)
        if identity.status not in (
            IdentityStatus.SELECTED,
            IdentityStatus.POOL,
            IdentityStatus.EXCLUSIVE,
        ):
            raise RegisterError(f"identity '{identity_id}' has not been selected")
        version = identity.latest
        if version.stage is not VersionStage.DRAFT:
            raise RegisterError(f"version {version.number} of '{identity_id}' is no longer a draft")
        if Capability.MULTI_REFERENCE not in self._engine.capabilities():
            raise RegisterError(
                f"engine '{identity.engine}' cannot work with reference images in this adapter"
            )

        # First version: the endorsed candidate image. Later versions: the
        # approved training set of the version the child grows out of.
        if version.parent is None:
            reference_hashes = [image.sha256 for image in version.images if image.role == "candidate"]
        else:
            reference_hashes = identity.versions[version.parent].dataset[:4]
        references = tuple(self._load_verified(identity_id, sha) for sha in reference_hashes)

        start = len(version.images) + identity.blocked_images
        created = []
        for index in range(start, start + count):
            image = self._generate_image(
                identity_id,
                version=version.number,
                role="dataset",
                prompt=self._prompt(
                    identity.description, version.age_years, f"same child, variation {index}"
                ),
                seed=self._seed(identity_id, version.number, index),
                references=references,
            )
            if image is not None:
                created.append(image)
        return created

    # -- 4. approve the training set -------------------------------------

    def approve_dataset(
        self, identity_id: str, reviewer: str, exclude: tuple[str, ...] = ()
    ) -> list[str]:
        _name(reviewer, "reviewer")
        identity = self.get(identity_id)
        version = identity.latest
        if version.stage is not VersionStage.DRAFT:
            raise RegisterError(f"version {version.number} of '{identity_id}' is no longer a draft")
        available = [image.sha256 for image in version.images if image.role == "dataset"]
        unknown = set(exclude) - set(available)
        if unknown:
            raise RegisterError(f"cannot exclude unknown images: {sorted(unknown)}")
        chosen = [sha for sha in available if sha not in exclude]
        if len(chosen) < MIN_DATASET_IMAGES:
            raise RegisterError(
                f"training set has {len(chosen)} images, at least {MIN_DATASET_IMAGES} are needed"
            )
        for sha in chosen:
            self._load_verified(identity_id, sha)
        for sha in exclude:
            self.image_path(identity_id, sha).unlink(missing_ok=True)
        self._record(
            identity_id,
            "dataset_approved",
            {
                "version": version.number,
                "reviewer": reviewer,
                "images": chosen,
                "excluded": list(exclude),
            },
        )
        return chosen

    # -- 5. train --------------------------------------------------------

    def train(self, identity_id: str, started_by: str) -> str:
        _name(started_by, "started_by")
        if self._trainer is None:
            raise RegisterError("no trainer is configured")
        identity = self.get(identity_id)
        self._require_engine(identity)
        version = identity.latest
        if version.stage is not VersionStage.DATASET_APPROVED:
            raise RegisterError(f"version {version.number} of '{identity_id}' has no approved training set")

        # Only the approved, signed and unchanged images reach the trainer.
        images = [self._load_verified(identity_id, sha) for sha in version.dataset]
        spec = TrainingSpec(
            identity_id=identity_id,
            version=version.number,
            engine=identity.engine,
            base_model_revision=self._engine.describe().model_revision,
            dataset_sha256=tuple(version.dataset),
            seed=self._seed(identity_id, version.number, 0),
        )
        weights = self._trainer.train(spec, images)
        path = self.lora_path(identity_id, version.number)
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(weights)
        (path.parent / "training.json").write_text(
            json.dumps(spec.as_dict(), indent=2), encoding="utf-8"
        )
        self._record(
            identity_id,
            "lora_trained",
            {
                "version": version.number,
                "weights_sha256": sha256_bytes(weights),
                "spec": spec.as_dict(),
                "spec_sha256": sha256_json(spec.as_dict()),
                "trainer": self._trainer.name,
                "trainer_production": self._trainer.production,
                "started_by": started_by,
            },
        )
        return sha256_bytes(weights)

    # -- 6. freeze -------------------------------------------------------

    def freeze(self, identity_id: str, by: str) -> int:
        _name(by, "by")
        identity = self.get(identity_id)
        version = identity.latest
        if version.stage is not VersionStage.TRAINED:
            raise RegisterError(f"version {version.number} of '{identity_id}' is not trained")
        self.verified_lora(identity_id, version.number, identity)
        self._record(identity_id, "version_frozen", {"version": version.number, "by": by})
        return version.number

    def verified_lora(
        self, identity_id: str, version: int, identity: Identity | None = None
    ) -> tuple[Path, str]:
        """Path and hash of a version's weights, after checking the file is unchanged."""
        identity = identity or self.get(identity_id)
        recorded = identity.versions[version].lora_sha256
        path = self.lora_path(identity_id, version)
        if recorded is None or not path.is_file() or sha256_bytes(path.read_bytes()) != recorded:
            raise RegisterError(f"LoRA weights of '{identity_id}' v{version} are missing or changed")
        return path, recorded

    # -- 7. pool and brand -----------------------------------------------

    def add_to_pool(self, identity_id: str, by: str) -> None:
        _name(by, "by")
        identity = self.get(identity_id)
        if identity.status is not IdentityStatus.SELECTED:
            raise RegisterError(f"identity '{identity_id}' cannot be pooled in state '{identity.status.value}'")
        if identity.latest.stage is not VersionStage.FROZEN:
            raise RegisterError("only a child with a frozen version can enter the pool")
        self._record(identity_id, "identity_pooled", {"by": by})

    def assign(self, identity_id: str, brand: str, by: str) -> None:
        """Lock the child to one brand. This cannot be undone or repeated."""
        _name(by, "by")
        _name(brand, "brand")
        identity = self.get(identity_id)
        if identity.status not in (IdentityStatus.SELECTED, IdentityStatus.POOL):
            raise RegisterError(
                f"identity '{identity_id}' cannot be assigned in state '{identity.status.value}'"
            )
        self._record(identity_id, "identity_assigned", {"brand": brand, "by": by})

    def retire(self, identity_id: str, by: str, reason: str = "") -> None:
        _name(by, "by")
        identity = self.get(identity_id)
        if identity.status in (IdentityStatus.RETIRED, IdentityStatus.REJECTED):
            raise RegisterError(f"identity '{identity_id}' is already '{identity.status.value}'")
        self._record(identity_id, "identity_retired", {"by": by, "reason": reason})

    # -- 8. grow ---------------------------------------------------------

    def grow(self, identity_id: str, age_years: int, by: str) -> int:
        """Start a new version with a higher age, derived from the latest frozen one."""
        _name(by, "by")
        _age(age_years)
        identity = self.get(identity_id)
        if identity.status not in (IdentityStatus.POOL, IdentityStatus.EXCLUSIVE, IdentityStatus.SELECTED):
            raise RegisterError(f"identity '{identity_id}' cannot grow in state '{identity.status.value}'")
        latest = identity.latest
        if latest.stage is not VersionStage.FROZEN:
            raise RegisterError(f"version {latest.number} must be frozen before the child can grow")
        if age_years <= latest.age_years:
            raise RegisterError(f"the new age must be above {latest.age_years}")
        number = latest.number + 1
        self._record(
            identity_id,
            "version_started",
            {"version": number, "age_years": age_years, "parent": latest.number, "by": by},
        )
        return number

    # -- use in a shooting -----------------------------------------------

    def resolve_for_shooting(
        self, identity_id: str, version: int, *, brand: str, age_years: int, engine: str
    ) -> tuple[bool, str, dict[str, Any]]:
        """Check that this child may appear in a shooting of this brand."""
        identity = self.all().get(identity_id)
        if identity is None:
            return False, f"unknown identity '{identity_id}'", {}
        if identity.status is not IdentityStatus.EXCLUSIVE or identity.brand != brand:
            return False, f"identity '{identity_id}' is not assigned to brand '{brand}'", {}
        if identity.engine != engine:
            return False, f"identity '{identity_id}' belongs to engine '{identity.engine}'", {}
        chosen = identity.versions.get(version)
        if chosen is None or chosen.stage is not VersionStage.FROZEN:
            return False, f"version {version} of '{identity_id}' is not frozen", {}
        if chosen.age_years != age_years:
            return False, f"version {version} of '{identity_id}' is {chosen.age_years} years old", {}
        try:
            _, lora = self.verified_lora(identity_id, version, identity)
        except RegisterError as error:
            return False, str(error), {}
        return True, "", {"identity_id": identity_id, "version": version, "lora_sha256": lora}
